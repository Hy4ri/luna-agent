#!/usr/bin/env python3
"""Split the Nerd Fonts symbols face into unicode-range chunks.

The browser downloads only the chunks that contain glyphs on the page. A sidebar
with a few project symbols then costs tens of kilobytes instead of the full 1 MB face.

Usage: python3 -I scripts/split-nerd-font.py   (needs fonttools and brotli)
Writes web/src/assets/fonts/nerd/*.woff2 and web/src/assets/fonts/nerd-symbols.css.
"""
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "web/src/assets/fonts"
SOURCE = FONTS / "SymbolsNerdFont-Regular.woff2"
OUT = FONTS / "nerd"
CHUNK = 64  # glyphs per chunk, about 7 kB of woff2
# Same coverage as the single face had: private-use planes only.
PRIVATE = [(0xE000, 0xF8FF), (0xF0000, 0xFFFFD), (0x100000, 0x10FFFD)]


def private(cp: int) -> bool:
    return any(lo <= cp <= hi for lo, hi in PRIVATE)


def main() -> None:
    cmap = sorted(cp for cp in TTFont(SOURCE).getBestCmap() if private(cp))
    OUT.mkdir(exist_ok=True)
    for old in OUT.glob("*.woff2"):
        old.unlink()
    faces = []
    for i in range(0, len(cmap), CHUNK):
        part = cmap[i:i + CHUNK]
        lo, hi = part[0], part[-1]
        name = f"nerd-{lo:x}-{hi:x}.woff2"
        options = subset.Options()
        options.flavor = "woff2"
        options.layout_features = []
        options.name_IDs = ["*"]  # keep the license and copyright names
        options.notdef_outline = True
        font = TTFont(SOURCE)
        subsetter = subset.Subsetter(options)
        subsetter.populate(unicodes=part)
        subsetter.subset(font)
        font.flavor = "woff2"
        font.save(OUT / name)
        faces.append((name, lo, hi))
    css = [
        "/* Generated by scripts/split-nerd-font.py from Nerd Fonts v3.4.0, Symbols Only.",
        "   See NERD-FONTS-LICENSE.txt. One face per glyph range: the browser fetches only ranges in use. */",
    ]
    for name, lo, hi in faces:
        css.append(
            '@font-face { font-family: "Luna Nerd Symbols"; src: url("./nerd/%s") format("woff2"); '
            "font-display: swap; unicode-range: U+%X-%X; }" % (name, lo, hi)
        )
    (FONTS / "nerd-symbols.css").write_text("\n".join(css) + "\n")
    total = sum((OUT / n).stat().st_size for n, _, _ in faces)
    print(f"{len(faces)} chunks, {total} bytes total, source {SOURCE.stat().st_size} bytes")


if __name__ == "__main__":
    main()
