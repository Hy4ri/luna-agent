// Real Chromium, real HTTP, real durable runtime; only model responses are scripted.
import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { serve } from "@hono/node-server";
import { createModels, fauxProvider, fauxAssistantMessage } from "@earendil-works/pi-ai";
import { context } from "./luna.js";
import { loadConfig, parseConfig } from "./config.js";
import { startRuntime } from "./runtime.js";
import { createApp } from "./server.js";
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.LUNA_PLAYWRIGHT_PATH || "playwright");
assert.deepEqual(parseConfig({}, process.cwd(), {}).busyInput, { mode: "interrupt", acknowledgements: true });
assert.throws(() => parseConfig({ busyInput: { mode: "redirect" } }, process.cwd(), {}), /busyInput/);
assert.throws(() => parseConfig({ busyInput: { unknown: true } }, process.cwd(), {}), /unknown/);
const dir = mkdtempSync(join(tmpdir(), "luna-busy-ui-")), path = join(dir, "config.json");
writeFileSync(path, JSON.stringify({ dataDir: dir, provider: "faux", extensions: [] }));
const faux = fauxProvider(), models = createModels(); models.setProvider(faux.provider);
const m = faux.getModel(), model = { provider: m.provider, modelId: m.id };
const rt = await startRuntime(loadConfig(path), { models, model });
const app = createApp({ harness: rt.harness, models, settings: rt.settings, conversations: rt.conversations, agent: { model }, token: "test" });
const server = serve({ fetch: app.fetch, hostname: "127.0.0.1", port: 0 });
await new Promise<void>(resolve => server.listening ? resolve() : server.once("listening", resolve));
let browser: any, release!: () => void;
try {
  const conv = await rt.harness.createConversation({ ownership: { kind: "ownerless" }, agent: { model } }, context);
  browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || "/usr/bin/chromium", headless: true, args: ["--no-sandbox", "--disable-dev-shm-usage", "--no-zygote", "--single-process", "--disable-gpu"] });
  const page = await browser.newPage({ viewport: { width: 1100, height: 900 } }); page.setDefaultTimeout(12000);
  const errors: string[] = []; page.on("pageerror", (e: Error) => errors.push(e.message));
  await page.addInitScript((id: string) => { localStorage.setItem("luna.token", "test"); localStorage.setItem("luna.session", id); }, String(conv.id));
  await page.goto(`http://127.0.0.1:${(server.address() as { port: number }).port}`);
  await page.locator('[data-panel="settings"]').click();
  await page.locator('[data-settings-tab="general"]').click();
  await page.locator('section[data-section="busyInput"]').waitFor();
  await page.getByLabel("Mode", { exact: true }).selectOption("queue");
  await page.getByLabel("Show acknowledgements", { exact: true }).uncheck();
  await page.locator("[data-settings-save]").click();
  await page.getByText("Settings saved. Compaction changes apply now. New sessions and subagents use the new defaults.", { exact: true }).waitFor();
  assert.deepEqual(rt.busyInput(), { mode: "queue", acknowledgements: false });
  assert.equal(rt.settings!.restartRequired, false);
  assert.deepEqual(JSON.parse(readFileSync(path, "utf8")).busyInput, rt.busyInput());
  await page.getByRole("button", { name: "Back to chat", exact: true }).click();
  let modelStarted!: () => void; const started = new Promise<void>(resolve => { modelStarted = resolve; });
  const held = new Promise<void>(resolve => { release = resolve; });
  faux.setResponses([async () => { modelStarted(); await held; return fauxAssistantMessage("Original answer"); }, fauxAssistantMessage("Queued answer")]);
  const messages: any[] = [];
  page.on("request", (req: any) => { if (/\/messages\?async=1$/.test(req.url())) messages.push(req.postDataJSON()); });
  await page.locator("#input").fill("original task"); await page.locator("#send").click(); await started;
  await page.locator("#stop").waitFor({ state: "visible" });
  await page.locator("#input").fill("/queue <b>queued task</b>"); await page.locator("#send").click();
  await page.locator("#stop").waitFor({ state: "visible" });
  await page.locator("#input").fill("/queue list"); await page.locator("#send").click();
  await page.locator("#busyFeedback").filter({ hasText: "1. <b>queued task</b>" }).waitFor();
  assert.equal(await page.locator("#busyFeedback b").count(), 0, "Queue text must not become HTML");
  assert.equal(messages.length, 3); assert.ok(messages.every(b => b.whenBusy === undefined));
  assert.equal(await page.locator("#log").getByText("/queue list", { exact: true }).count(), 0);
  assert.ok(!(await page.locator("#busyFeedback").textContent()).includes("Queued."), "Acknowledgements disabled");
  release(); await conv.waitForIdle(context);
  await page.locator("#log").getByText("Queued answer", { exact: true }).waitFor();
  assert.equal(await page.locator("#log").getByText("<b>queued task</b>", { exact: true }).count(), 1);
  const second = await rt.harness.createConversation({ ownership: { kind: "ownerless" }, agent: { model } }, context);
  await page.evaluate((id: string) => (globalThis as any).openSession(id), String(second.id));
  assert.equal(await page.locator("#busyFeedback").isVisible(), false, "Do not show previous session feedback");
  assert.deepEqual(errors, []);
  console.log("BUSY_INPUT_UI_OK: live settings persisted, default routing, slash queue commands, escaped feedback, no duplicate user rows");
} finally {
  release?.(); await browser?.close(); await new Promise<void>(resolve => server.close(() => resolve())); await rt.close(); rmSync(dir, { recursive: true, force: true });
}
