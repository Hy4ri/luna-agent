// Real Chromium + HTTP + durable runtime. Only the model is scripted.
import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { serve } from "@hono/node-server";
import { createModels, fauxProvider, fauxAssistantMessage } from "@earendil-works/pi-ai";
import { UserEntry, AssistantEntry } from "@earendil-works/pi-durable";
import { loadConfig } from "./config.js";
import { startRuntime } from "./runtime.js";
import { createApp } from "./server.js";
import { context } from "./luna.js";
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.LUNA_PLAYWRIGHT_PATH || "playwright");
const dir = mkdtempSync(join(tmpdir(), "luna-compaction-ui-"));
const config = join(dir, "config.json");
writeFileSync(config, JSON.stringify({ dataDir: dir, provider: "faux", extensions: [] }));
const faux = fauxProvider({ models: [{ id: "small", contextWindow: 4000 }, { id: "large", contextWindow: 8000 }, { id: "unknown", contextWindow: 0 }] });
const models = createModels(); models.setProvider(faux.provider);
const m = faux.getModel(), model = { provider: m.provider, modelId: m.id };
const rt = await startRuntime(loadConfig(config), { models, model });
const app = createApp({ harness: rt.harness, models, settings: rt.settings, conversations: rt.conversations, agent: { model }, token: "test" });
const server = serve({ fetch: app.fetch, hostname: "127.0.0.1", port: 0 });
await new Promise<void>(resolve => server.listening ? resolve() : server.once("listening", resolve));
let browser: any;
let releaseSummary!: () => void;
let releaseContext: (() => void) | undefined;
try {
  const conv = await rt.harness.createConversation({ ownership: { kind: "ownerless" }, agent: { model } }, context);
  browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || "/usr/bin/chromium", headless: true, args: ["--no-sandbox", "--disable-dev-shm-usage", "--no-zygote", "--single-process", "--disable-gpu"] });
  const page = await browser.newPage({ viewport: { width: 1100, height: 900 } });
  page.setDefaultTimeout(12000);
  const errors: string[] = [];
  page.on("pageerror", (e: Error) => errors.push(e.message));
  await page.addInitScript((id: string) => { localStorage.setItem("luna.token", "test"); localStorage.setItem("luna.session", id); }, String(conv.id));
  await page.goto(`http://127.0.0.1:${(server.address() as { port: number }).port}`);
  await page.locator("#context-bar").waitFor({ state: "visible" });
  await page.waitForFunction(() => (globalThis as any).document.getElementById("context-bar")?.dataset.level === "green");
  assert.match(await page.locator("#context-text").textContent(), /4,000/);
  await conv.commit(async tx => {
    await tx.appendEntry(UserEntry, conv.id, { model: [{ role: "user", content: "x".repeat(8000), timestamp: 1 }] });
  }, context);
  await page.waitForFunction(() => (globalThis as any).document.getElementById("context-bar")?.dataset.level === "amber");
  const report = async (tokens: number) => conv.commit(async tx => {
    const answer = fauxAssistantMessage("Reported usage");
    answer.usage.totalTokens = tokens;
    await tx.appendEntry(AssistantEntry, conv.id, { model: [answer] });
  }, context);
  await report(3200);
  await page.waitForFunction(() => (globalThis as any).document.getElementById("context-bar")?.dataset.level === "red");
  assert.equal(await page.locator("#context-meter").getAttribute("aria-valuenow"), "80");
  await report(4400);
  await page.waitForFunction(() => (globalThis as any).document.getElementById("context-text")?.textContent?.includes("110.0%"));
  assert.equal(await page.locator("#context-meter").getAttribute("aria-valuenow"), "100");
  assert.equal(await page.locator("#context-fill").evaluate((e: any) => e.style.width), "100%");
  await report(1400);
  await page.waitForFunction(() => (globalThis as any).document.getElementById("context-bar")?.dataset.level === "green");
  await page.locator('[data-panel="settings"]').click();
  const section = page.locator('details[data-section="compaction"]');
  await section.locator("summary").click();
  await page.getByLabel("Enable automatic compaction", { exact: true }).uncheck();
  await page.getByLabel("Context trigger (%)", { exact: true }).fill("30");
  await page.locator("[data-settings-save]").click();
  await page.waitForFunction(() => [...(globalThis as any).document.querySelectorAll('[role="status"][aria-live="polite"]')].some(e => e.textContent?.includes("Compaction changes apply now")));
  assert.deepEqual(rt.compaction(), { enabled: false, triggerPercent: 30 });
  await page.waitForFunction(() => (globalThis as any).document.getElementById("context-bar")?.dataset.level === "red");
  // Closing the panel keeps the same attached conversation.
  await page.keyboard.press("Escape");
  await report(1400);
  await page.waitForFunction(() => (globalThis as any).document.getElementById("context-text")?.textContent?.includes("35.0%"));
  assert.equal(await page.locator("#context-bar").getAttribute("data-level"), "red", "Trigger below 50% takes precedence");
  await conv.configure({ model: { provider: m.provider, modelId: "large" } }, context);
  await page.waitForFunction(() => (globalThis as any).document.getElementById("context-text")?.textContent?.includes("8,000"));
  assert.equal(await page.locator("#context-bar").getAttribute("data-level"), "green");
  await conv.configure({ model: { provider: m.provider, modelId: "unknown" } }, context);
  await page.waitForFunction(() => (globalThis as any).document.getElementById("context-text")?.textContent?.includes("capacity unavailable"));
  assert.equal(await page.locator("#context-meter").isVisible(), false);
  // A delayed response from the old owner must not overwrite the new conversation's bar.
  await conv.configure({ model }, context);
  await page.waitForFunction(() => (globalThis as any).document.getElementById("context-text")?.textContent?.includes("4,000"));
  let contextRequested!: () => void, contextDelivered!: () => void;
  const requested = new Promise<void>(r => { contextRequested = r; });
  const delivered = new Promise<void>(r => { contextDelivered = r; });
  const responseGate = new Promise<void>(r => { releaseContext = r; });
  const oldPath = `**/v1/sessions/${conv.id}/context`;
  await page.route(oldPath, async (route: any) => {
    const response = await route.fetch(); contextRequested();
    await responseGate; await route.fulfill({ response }); contextDelivered();
  });
  await report(3800); await requested;
  const empty = await rt.harness.createConversation({ ownership: { kind: "ownerless" }, agent: { model } }, context);
  await page.evaluate((id: string) => (globalThis as any).openSession(id), String(empty.id));
  await page.waitForFunction(() => (globalThis as any).document.getElementById("context-text")?.textContent?.includes("≈0 /"));
  releaseContext!(); await delivered;
  await page.waitForTimeout(120);
  assert.match(await page.locator("#context-text").textContent(), /≈0 \//);
  await page.unroute(oldPath);
  // Real auto-compaction: final answer waits for the summarizer; no extra turn follows.
  rt.settings!.update(s => { s.compaction = { enabled: true, triggerPercent: 75 }; });
  const finalConv = await rt.harness.createConversation({ ownership: { kind: "ownerless" }, agent: { model } }, context);
  await finalConv.commit(async tx => {
    await tx.appendEntry(UserEntry, finalConv.id, { model: [{ role: "user", content: "old ".repeat(1800), timestamp: 1 }] });
    await tx.appendEntry(AssistantEntry, finalConv.id, { model: [fauxAssistantMessage("Earlier reply")] });
  }, context);
  await page.evaluate((id: string) => (globalThis as any).openSession(id), String(finalConv.id));
  const summaryGate = new Promise<void>(resolve => { releaseSummary = resolve; });
  faux.setResponses([fauxAssistantMessage("Final answer ".repeat(550)), async () => { await summaryGate; return fauxAssistantMessage("Earlier work complete."); }]);
  const sub = await finalConv.submit({ type: "input", content: "Finish" }, context);
  await page.waitForFunction(() => (globalThis as any).document.getElementById("status")?.textContent === "Compacting context…");
  assert.equal(faux.state.callCount, 2, "Only answer + summary requests");
  releaseSummary();
  assert.equal((await sub.wait(context)).status, "done");
  await page.waitForFunction(() => (globalThis as any).document.getElementById("status")?.textContent === "Ready");
  assert.equal(faux.state.callCount, 2, "Compaction must not invent another turn");
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => (globalThis as any).document.documentElement.scrollWidth <= (globalThis as any).innerWidth), true);
  await page.locator("#new").evaluate((e: any) => e.click());
  await page.waitForFunction(() => (globalThis as any).document.getElementById("context-text")?.textContent?.includes("≈0 /"));
  await page.waitForFunction(() => (globalThis as any).document.getElementById("status")?.textContent === "Ready");
  assert.deepEqual(errors, []);
  console.log("COMPACTION_UI_OK: real settings, colors, overflow display, unknown capacity, model switch, live summary pause, idle, mobile layout");
} finally {
  releaseSummary?.(); releaseContext?.(); await browser?.close(); (server as any).closeAllConnections(); await new Promise<void>(resolve => server.close(() => resolve()));
  await rt.close(); rmSync(dir, { recursive: true, force: true });
}
