// Real browser gate: isolated runtime, SQLite, HTTP, Chromium. No paid model calls.
import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { serve } from "@hono/node-server";
import { createModels, fauxProvider, fauxAssistantMessage, fauxText } from "@earendil-works/pi-ai";
import { parseConfig } from "./config.js";
import { startRuntime } from "./runtime.js";
import { createApp } from "./server.js";
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.LUNA_PLAYWRIGHT_PATH || "playwright");
const dir = mkdtempSync(join(tmpdir(), "luna-cron-screen-ui-"));
const faux = fauxProvider(), models = createModels(); models.setProvider(faux.provider);
const fm = faux.getModel(), model = { provider: fm.provider, modelId: fm.id };
faux.setResponses(Array.from({ length: 10 }, () => fauxAssistantMessage([fauxText("Manual run complete")])));
const rt = await startRuntime(parseConfig({ dataDir: dir, provider: "faux" }, dir, {}), { models, model });
const store = rt.store!;
let clock = Date.now() - 100000;
const hourly = store.addJob("Hourly Check", "0 * * * *", "Check status", model);
let latestId = 0;
for (let i = 0; i < 26; i++) {
  const run = store.claimManual(hourly, ++clock); latestId = run.id;
  store.finish(run.id, "ok", i === 25 ? "## Full report\nAll systems nominal\n" + "Long report text. ".repeat(250) : `Old report ${i}`, null, ++clock);
}
const failing = store.addJob("Daily Failure", "@daily", "Check errors", model);
const failedRun = store.claimManual(failing, ++clock); store.finish(failedRun.id, "error", null, "A visible failure", ++clock);
const live = store.addJob("Live Check", "@daily", "Live state", model);
const activeRun = store.claimManual(live, ++clock);
const script = store.addJob("Imported script", "* * * * *", "");
store.db.prepare("UPDATE jobs SET execution=?,interval_ms=? WHERE id=?").run(JSON.stringify({ command: ["not-executed", "--check"], cwd: "/tmp" }), 300000, script.id);
store.setEnabled(script.id, false);
const app = createApp({ harness: rt.harness, models, conversations: rt.conversations, agent: { model }, store, scheduler: rt.scheduler, token: "test" });
const server = serve({ fetch: app.fetch, hostname: "127.0.0.1", port: 0 });
await new Promise<void>(resolve => server.listening ? resolve() : server.once("listening", resolve));
let browser: any;
try {
  browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || "/usr/bin/chromium", headless: true, args: ["--no-sandbox", "--disable-dev-shm-usage", "--no-zygote", "--single-process", "--disable-gpu"] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(12000);
  const errors: string[] = [], historyRequests: string[] = [];
  page.on("pageerror", (error: Error) => errors.push(error.message));
  page.on("request", (request: any) => { if (/\/v1\/cron\/(reports|runs)\?/.test(request.url()) && request.url().includes("history=1")) historyRequests.push(request.url()); });
  await page.goto(`http://127.0.0.1:${(server.address() as { port: number }).port}`);
  await page.locator("#token").fill("test"); await page.locator("#loginForm button").click();
  await page.locator("#login").waitFor({ state: "hidden" });
  await page.locator('[data-panel="cron"]').click();
  const screen = page.locator("#cron-screen"), latest = screen.locator('[data-cron-list="latest"]'), history = screen.locator("details.cron-history");
  await screen.waitFor(); await latest.locator(`[data-run="${latestId}"]`).waitFor();
  assert.equal(await page.locator("#panel").isVisible(), false);
  assert.equal(await page.locator("#main").isVisible(), false);
  assert.equal(historyRequests.length, 0, "Old reports must not load before history opens");
  assert.equal(await latest.locator("[data-run]").count(), 2);
  assert.equal(store.unreadCount(), 2, "unreadCount reflects unread latest reports, not historical reports");
  assert.equal(Number(await page.locator("#cron-unread").textContent()), 2);
  const report = latest.locator(`[data-run="${latestId}"]`), inspector = screen.locator("[data-cron-inspector]");
  await report.click(); await inspector.getByRole("heading", { name: "Full report" }).waitFor();
  await inspector.getByRole("button", { name: "Mark unread", exact: true }).waitFor();
  assert.ok(store.getRun(latestId)!.readAt);
  assert.equal(Number(await page.locator("#cron-unread").textContent()), 1);
  assert.ok((await inspector.locator(".md").textContent()).length > 3000, "Full report must not truncate");
  await inspector.getByRole("button", { name: "Mark unread", exact: true }).click();
  await report.filter({ hasText: "Unread" }).waitFor();
  assert.equal(store.getRun(latestId)!.readAt, null);
  assert.equal(Number(await page.locator("#cron-unread").textContent()), 2);
  await history.locator(":scope > summary").click();
  await history.locator("[data-run]").first().waitFor();
  assert.equal(await history.locator("[data-run]").count(), 20);
  // Hold an older polling response, then request another history page. The old poll must not erase that page.
  let releaseHistory!: () => void, historyArrived!: () => void, historyDelivered!: () => void;
  const historyGate = new Promise<void>(resolve => { releaseHistory = resolve; });
  const arrived = new Promise<void>(resolve => { historyArrived = resolve; });
  const delivered = new Promise<void>(resolve => { historyDelivered = resolve; });
  await page.route("**/v1/cron/reports?*", async (route: any) => {
    const url = new URL(route.request().url());
    if (url.searchParams.get("history") === "1" && !url.searchParams.has("before")) {
      const response = await route.fetch(); historyArrived(); await historyGate;
      await route.fulfill({ response }); historyDelivered();
    } else await route.continue();
  });
  await Promise.race([arrived, new Promise((_, reject) => setTimeout(() => reject(new Error("History polling request missing")), 10000))]);
  await history.getByRole("button", { name: "Load more history", exact: true }).click();
  await page.waitForFunction(() => (globalThis as any).document.querySelectorAll('#cron-screen .cron-history [data-run]').length === 25);
  releaseHistory(); await delivered; await page.waitForTimeout(150);
  assert.equal(await history.locator("[data-run]").count(), 25, "Stale polling response must not remove loaded history pages");
  await page.unroute("**/v1/cron/reports?*");
  assert.ok(historyRequests.length > 0);
  await history.locator(":scope > summary").click();
  console.log("OK full-page reports, safe full markdown, read/unread badge, lazy history and pagination");

  await screen.getByLabel("Cron sections").getByRole("button", { name: "Jobs", exact: true }).click();
  const job = (id: number) => screen.locator(`[data-job="${id}"].cron-job`);
  await job(hourly.id).waitFor();
  await job(script.id).getByText("Every 5 minutes", { exact: true }).waitFor();
  await job(script.id).getByText(/not-executed --check/).waitFor();
  assert.equal(await job(live.id).getByRole("button", { name: "Run now", exact: true }).isDisabled(), true);
  await screen.getByRole("button", { name: "New job", exact: true }).click();
  await screen.getByLabel("Job name", { exact: true }).fill("Test Job");
  await screen.getByLabel("Schedule", { exact: true }).fill("*/5 * * * *");
  await screen.getByLabel("Prompt", { exact: true }).fill("Run test prompt");
  await screen.getByLabel("Reporting", { exact: true }).selectOption("changes");
  await screen.getByRole("button", { name: "Save job", exact: true }).click();
  await latest.getByText("Test Job", { exact: true }).waitFor();
  const created = store.listJobs().find(j => j.name === "Test Job")!;
  await job(created.id).getByRole("button", { name: "Edit", exact: true }).click();
  await screen.getByLabel("Job name", { exact: true }).fill("Test Job Updated");
  await screen.getByRole("button", { name: "Save job", exact: true }).click();
  await job(created.id).getByText("Test Job Updated", { exact: true }).waitFor();
  // Failure is injected into the actual pause endpoint. The job must stay enabled.
  await page.route(`**/v1/cron/${created.id}`, (route: any) => route.fulfill({ status: 409, json: { error: "Injected pause failure" } }));
  await job(created.id).getByRole("button", { name: "Pause", exact: true }).click();
  await screen.getByRole("status").filter({ hasText: "Injected pause failure" }).waitFor();
  assert.equal(store.getJob(created.id)!.enabled, true);
  await page.unroute(`**/v1/cron/${created.id}`);
  await job(created.id).getByRole("button", { name: "Pause", exact: true }).click();
  await job(created.id).getByRole("button", { name: "Resume", exact: true }).waitFor();
  await job(created.id).getByRole("button", { name: "Resume", exact: true }).click();
  await job(created.id).getByRole("button", { name: "Run now", exact: true }).click();
  await rt.scheduler!.idle();
  await page.waitForFunction((id: number) => (globalThis as any).document.querySelector(`[data-job="${id}"].cron-job`)?.textContent?.includes("Last result: ok"), created.id);
  const createdRun = store.runs(created.id)[0]!;
  page.once("dialog", (dialog: any) => dialog.accept());
  await job(created.id).getByRole("button", { name: "Delete", exact: true }).click();
  await job(created.id).waitFor({ state: "detached" });
  assert.equal(store.getJob(created.id), undefined); assert.ok(store.getRun(createdRun.id));
  console.log("OK job create/edit/reporting, script interval display, active-run controls, failure feedback, pause/resume/run/delete preserving history");

  await screen.getByLabel("Cron sections").getByRole("button", { name: "Runs", exact: true }).click();
  await latest.locator(`[data-run="${activeRun.id}"]`).waitFor();
  await latest.locator(`[data-run="${failedRun.id}"]`).waitFor();
  assert.equal(await latest.locator(`[data-run="${latestId}"]`).count(), 0, "Successes stay out of the default run list");
  await screen.getByLabel("Status", { exact: true }).selectOption("error");
  await latest.locator(`[data-run="${failedRun.id}"]`).waitFor();
  assert.equal(await latest.locator(`[data-run="${activeRun.id}"]`).count(), 0);
  await screen.getByLabel("Job", { exact: true }).selectOption(String(failing.id));
  await latest.locator(`[data-run="${failedRun.id}"]`).click();
  await inspector.getByText("Error: A visible failure", { exact: true }).waitFor();
  await inspector.getByText(/Conversation:/).waitFor();
  // Continue creates an empty conversation and a visible draft, never sends a model request.
  await inspector.getByRole("button", { name: "Continue in chat", exact: true }).click();
  await screen.waitFor({ state: "hidden" });
  assert.ok((await page.locator("#input").inputValue()).includes("A visible failure"));
  assert.ok((await page.locator("#input").inputValue()).includes(`#${failedRun.id}`));
  const sid = await page.evaluate(() => localStorage.getItem("luna.session"));
  assert.equal(sid, null, "Continue in chat leaves an unsent local draft without creating a server session");
  assert.equal(await page.locator("#log .msg.user").count(), 0);
  console.log("OK runs filters/details and Continue in chat creates an unsent draft");

  await page.setViewportSize({ width: 320, height: 844 }); await page.locator("#menu").click();
  await page.locator('[data-panel="cron"]').click(); await screen.waitFor();
  await screen.getByLabel("Cron sections").getByRole("button", { name: "Jobs", exact: true }).click();
  await screen.getByRole("button", { name: "New job", exact: true }).click();
  const nameField = screen.getByLabel("Job name", { exact: true });
  await nameField.fill("Unsaved Draft"); await nameField.focus();
  store.finish(activeRun.id, "error", null, "Live error now", ++clock);
  await page.waitForFunction((id: number) => (globalThis as any).document.querySelector(`[data-job="${id}"].cron-job`)?.textContent?.includes("Last result: error"), live.id);
  assert.equal(await nameField.inputValue(), "Unsaved Draft"); assert.equal(await nameField.evaluate((el: any) => el === (globalThis as any).document.activeElement), true);
  assert.equal(await page.evaluate(() => (globalThis as any).document.documentElement.scrollWidth <= (globalThis as any).innerWidth), true);
  await page.screenshot({ path: "/tmp/luna-cron-mobile.png", fullPage: true });
  await screen.getByRole("button", { name: "Cancel", exact: true }).click();
  await page.locator("#cron-menu").click(); await page.locator("#side-close").click();
  assert.equal(await screen.evaluate((el: any) => el.inert), false);
  await page.reload(); await screen.waitFor();
  assert.equal(await page.locator("#panel").isVisible(), false);
  // A rejected token closes the Cron page and leaves it inert behind login. Reauthentication restores #cron.
  await page.route("**/v1/cron?summary=1", (route: any) => route.fulfill({ status: 401, json: { error: "unauthorized" } }));
  await page.locator("#login").waitFor({ state: "visible" });
  assert.equal(await screen.isVisible(), false);
  assert.equal(await screen.count(), 0, "Cron view is unmounted during login");
  assert.equal(await page.locator("#main").evaluate((el: any) => el.inert), true, "Chat is inert behind login");
  await page.unroute("**/v1/cron?summary=1");
  await page.locator("#token").fill("test"); await page.locator("#loginForm button").click();
  await page.locator("#login").waitFor({ state: "hidden" }); await screen.waitFor();
  assert.deepEqual(errors, []);
  console.log("CRON_SCREEN_UI_OK: live polling preserves form/focus, 320px layout, mobile navigation, hash reload, zero browser errors");
} finally {
  await browser?.close(); await new Promise<void>(resolve => server.close(() => resolve())); await rt.close(); rmSync(dir, { recursive: true, force: true });
}
process.exit(0);
