import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { serve } from "@hono/node-server";
import { createModels, fauxProvider, fauxAssistantMessage } from "@earendil-works/pi-ai";
import { context } from "./luna.js";
import { parseConfig } from "./config.js";
import { startRuntime } from "./runtime.js";
import { createApp } from "./server.js";
const dir = mkdtempSync(join(tmpdir(), "luna-side-cli-"));
const faux = fauxProvider(), models = createModels(); models.setProvider(faux.provider);
const fm = faux.getModel(), model = { provider: fm.provider, modelId: fm.id };
const rt = await startRuntime(parseConfig({ dataDir: dir, cwd: dir, extensions: [] }, dir, {}), { models, model, log: () => {} });
const app = createApp({ harness: rt.harness, models, sideCommands: rt.sideCommands, agent: { model }, token: "test" });
const server = serve({ fetch: app.fetch, hostname: "127.0.0.1", port: 0 });
await new Promise<void>(r => server.listening ? r() : server.once("listening", r));
const run = promisify(execFile);
const env = { ...process.env, LUNA_TOKEN: "test", LUNA_URL: `http://127.0.0.1:${(server.address() as { port: number }).port}` };
try {
  const conv = await rt.harness.createConversation({ ownership: { kind: "ownerless" }, agent: { model } }, context);
  faux.setResponses([fauxAssistantMessage("seed answer")]);
  await (await conv.submit({ type: "input", content: "seed history" }, context)).wait(context);
  const before = (await conv.context(context)).messages;
  faux.setResponses([fauxAssistantMessage("CLI_BACKGROUND_RESULT")]);
  const bg = await run(process.execPath, ["--import", "tsx", "src/cli.ts", "--session", String(conv.id), "/bg", "background"], { env, timeout: 15000 });
  assert.match(bg.stderr, /\/bg started:/); assert.match(bg.stdout, /\/bg complete: background/); assert.match(bg.stdout, /CLI_BACKGROUND_RESULT/);
  faux.setResponses([fauxAssistantMessage("CLI_SIDE_RESULT")]);
  const btw = await run(process.execPath, ["--import", "tsx", "src/cli.ts", "--session", String(conv.id), "/btw", "question"], { env, timeout: 15000 });
  assert.match(btw.stderr, /\/btw started:/); assert.match(btw.stdout, /\/btw complete: question/); assert.match(btw.stdout, /CLI_SIDE_RESULT/);
  const queue = await run(process.execPath, ["--import", "tsx", "src/cli.ts", "--session", String(conv.id), "/queue", "list"], { env, timeout: 15000 });
  assert.ok(!queue.stdout.includes("CLI_SIDE_RESULT"));
  assert.deepEqual((await conv.context(context)).messages, before);
  console.log("SIDE_CLI_OK: real CLI prints started and asynchronous results; queue commands retained; no source writes");
} finally { await new Promise<void>(r => server.close(() => r())); await rt.close(); rmSync(dir, { recursive: true, force: true }); }
